import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

for (const direction of ['horizontal', 'vertical', 'both']) test(`page mirror ${direction}: Undo, draw, select text, erase, export and reopen keep one coordinate frame`, async ({ page }) => {
  await page.route('**/*', route => /^https?:\/\/(127\.0\.0\.1|localhost)(:|\/)/.test(route.request().url()) ? route.continue() : route.abort());
  await page.goto('/?testPdf=text-selection-rotation-matrix.pdf');
  const first = page.locator('.survey-pdfjs-page-div[data-page-number="1"]');
  await expect(first).toBeVisible({ timeout: 20000 });
  await page.waitForTimeout(1000);
  await page.getByRole('button', { name: 'Pages', exact: true }).click();
  await page.locator('[data-page-card]').first().click({ button: 'right' });
  const firstAxis = direction === 'vertical' ? 'vertically' : 'horizontally';
  const firstMatrix = direction === 'vertical' ? 'matrix(1, 0, 0, -1, 0, 0)' : 'matrix(-1, 0, 0, 1, 0, 0)';
  const finalMatrix = direction === 'both' ? 'matrix(-1, 0, 0, -1, 0, 0)' : firstMatrix;
  await page.getByRole('menuitem', { name: `Mirror ${firstAxis}`, exact: true }).click();
  await expect(first).toHaveCSS('transform', firstMatrix);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(first).toHaveCSS('transform','none');
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await expect(first).toHaveCSS('transform', firstMatrix);
  if (direction === 'both') {
    await page.locator('[data-page-card]').first().click({ button: 'right' });
    await page.getByRole('menuitem', { name: 'Mirror vertically', exact: true }).click();
    await expect(first).toHaveCSS('transform', finalMatrix);
  }
  await page.getByRole('button', { name: 'Pages', exact: true }).click();
  const box=await page.locator('[data-svg-annotation-layer="1"]').boundingBox();
  await page.keyboard.press('r');
  await page.mouse.move(box.x+180,box.y+260);await page.mouse.down();
  await page.mouse.move(box.x+330,box.y+360,{steps:10});await page.mouse.up();
  await page.keyboard.press('v');
  await page.mouse.click(box.x+180,box.y+310);
  await expect(page.locator('[data-selection-context-index]')).toHaveCount(1);
  const rectangle=await page.locator('[data-selection-context-hitbox]').boundingBox();
  expect(Math.abs(rectangle.x-(box.x+180))).toBeLessThan(2);
  expect(Math.abs(rectangle.width-150)).toBeLessThan(2);
  await page.keyboard.press('Shift+v');
  const text=page.locator('.survey-pdfjs-page-div[data-page-number="1"] .pdfjsTextLayer span').nth(1);
  await expect(text).toBeVisible();
  const span=await text.boundingBox();
  await page.mouse.move(span.x+span.width-2,span.y+span.height/2);await page.mouse.down();
  await page.mouse.move(span.x+span.width*0.5,span.y+span.height/2,{steps:12});await page.mouse.up();
  await expect(page.locator('[data-text-selection-quick-menu][data-visible="true"]')).toBeVisible();
  const selectionRect=await page.evaluate(()=>{const r=window.getSelection().getRangeAt(0).getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height};});
  await page.getByRole('button',{name:'Add highlight on selected text',exact:true}).click();
  const highlight=page.locator('[data-shape-kind="text-markup-highlight"]');
  await expect(highlight).toHaveCount(1);
  const highlightRect=await highlight.boundingBox();
  expect(Math.abs(highlightRect.x-selectionRect.x)).toBeLessThan(3);
  expect(Math.abs(highlightRect.width-selectionRect.width)).toBeLessThan(3);
  await page.keyboard.press('p');
  await page.mouse.move(box.x+200,box.y+450);await page.mouse.down();await page.mouse.move(box.x+400,box.y+450,{steps:15});await page.mouse.up();
  const ink=page.locator('[data-svg-annotation-layer="1"] [data-path-hit-target="true"]').first();
  await expect(ink).toHaveCount(1);
  const before=await ink.getAttribute('d');
  await page.keyboard.press('e');
  await page.mouse.move(box.x+300,box.y+435);await page.mouse.down();await page.mouse.move(box.x+300,box.y+465,{steps:8});await page.mouse.up();
  await expect.poll(()=>ink.getAttribute('d')).not.toBe(before);
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export annotated PDF',exact:true}).click();
  const bytes=await readFile(await (await download).path());
  await page.route('**/debug-fixtures/mirror-roundtrip.pdf',route=>route.fulfill({status:200,contentType:'application/pdf',body:bytes}));
  await page.goto('/?testPdf=mirror-roundtrip.pdf');
  await expect(first).toBeVisible({ timeout:20000 });
  await expect(first).toHaveCSS('transform', finalMatrix);
  await expect(page.locator('[data-shape-kind="text-markup-highlight"]')).toHaveCount(1);
  const restored=await page.locator('[data-shape-kind="text-markup-highlight"]').boundingBox();
  expect(Math.abs(restored.x-highlightRect.x)).toBeLessThan(3);
  expect(Math.abs(restored.width-highlightRect.width)).toBeLessThan(3);
  await page.screenshot({path:test.info().outputPath('mirror-roundtrip.png')});
});

async function regionGeometryBox(locator) {
  return locator.evaluate(element=>{const b=element.getBBox(),m=element.getScreenCTM(),points=[[b.x,b.y],[b.x+b.width,b.y],[b.x,b.y+b.height],[b.x+b.width,b.y+b.height]].map(([x,y])=>new DOMPoint(x,y).matrixTransform(m));const xs=points.map(p=>p.x),ys=points.map(p=>p.y);return {x:Math.min(...xs),y:Math.min(...ys),width:Math.max(...xs)-Math.min(...xs),height:Math.max(...ys)-Math.min(...ys)};});
}
for (const direction of ['horizontal','vertical','both']) test(`mirrored regions ${direction}: draw, move, vertex handles and full page`,async({page})=>{
  await page.route('**/*',route=>/^https?:\/\/(127\.0\.0\.1|localhost)(:|\/)/.test(route.request().url())?route.continue():route.abort());
  await page.goto('/?testPdf=order-pages.pdf');
  await page.waitForFunction(()=>window.__fix19SurveyRegionHarness);
  await page.evaluate(()=>window.__fix19SurveyRegionHarness.setup());
  await page.getByRole('button',{name:'Pages',exact:true}).click();
  for(const axis of direction==='both'?['horizontally','vertically']:[direction==='vertical'?'vertically':'horizontally']) {
    await page.locator('[data-page-card]').first().click({button:'right'});
    await page.getByRole('menuitem',{name:`Mirror ${axis}`,exact:true}).click();
  }
  await page.getByRole('button',{name:'Spaces',exact:true}).click();
  await page.getByRole('button',{name:'Open Fix19 Space A',exact:true}).click();
  const editSpaces=page.getByRole('button',{name:'Edit Spaces',exact:true});
  if(await editSpaces.count())await editSpaces.click();
  await page.getByRole('button',{name:/^Edit the (areas|regions) on page 1$/}).click();
  await expect(page.locator('[data-region-edit-layer]')).toBeVisible();
  await page.getByRole('button',{name:/^Rectangle (area|region)$/}).click();
  const target=page.locator('.survey-pdfjs-page-div[data-page-number="1"]');
  const box=await target.boundingBox();
  const x=direction==='vertical'?430:40,y=430;
  await page.mouse.move(box.x+x,box.y+y);await page.mouse.down();await page.mouse.move(box.x+x+70,box.y+y+60,{steps:10});await page.mouse.up();
  const area=page.locator('[data-region-edit-layer] [data-region-id]').last();
  await expect(area).toBeVisible();
  const drawn=await regionGeometryBox(area);
  expect(Math.abs(drawn.x-(box.x+x))).toBeLessThan(3);
  expect(Math.abs(drawn.y-(box.y+y))).toBeLessThan(3);
  expect(Math.abs(drawn.width-70)).toBeLessThan(3);
  await page.locator('[data-select-tool="true"]').click();
  await page.mouse.move(drawn.x+drawn.width/2,drawn.y+drawn.height/2);await page.mouse.down();await page.mouse.move(drawn.x+drawn.width/2+25,drawn.y+drawn.height/2+20,{steps:8});await page.mouse.up();
  const moved=await regionGeometryBox(area);
  expect(Math.abs(moved.x-drawn.x-25)).toBeLessThan(3);
  expect(Math.abs(moved.y-drawn.y-20)).toBeLessThan(3);
  const vertex=page.locator('[data-region-vertex-handle="0"]').first();
  await expect(vertex).toBeVisible();
  const before=await vertex.boundingBox();
  await page.mouse.move(before.x+before.width/2,before.y+before.height/2);await page.mouse.down();await page.mouse.move(before.x+before.width/2+15,before.y+before.height/2+10,{steps:8});await page.mouse.up();
  const after=await vertex.boundingBox();
  expect(Math.abs(after.x-before.x-15)).toBeLessThan(3);
  expect(Math.abs(after.y-before.y-10)).toBeLessThan(3);
  await page.keyboard.press('Enter');
  const stored=await page.evaluate(()=>{const key=Object.keys(localStorage).find(value=>value.startsWith('pdfSidebar_order-pages.pdf'));return JSON.parse(localStorage.getItem(key));});
  const entry=stored.spaces.find(space=>space.id==='fix19-space-a').assignedPages[0];
  expect(entry.regions.length).toBeGreaterThan(0);
  for(const region of entry.regions)for(const coordinate of region.coordinates||[])expect(Number.isFinite(coordinate)).toBe(true);
  const sx=(after.x+after.width/2-box.x)/box.width*600,sy=(after.y+after.height/2-box.y)/box.height*792;
  const originalPoint={x:direction==='vertical'?sx:600-sx,y:direction==='horizontal'?sy:792-sy};
  const hasEditedPoint=entry.regions.some(region=>(region.coordinates||[]).some((coordinate,index,coords)=>index%2===0 && Math.abs(coordinate-originalPoint.x)<3 && Math.abs(coords[index+1]-originalPoint.y)<3));
  expect(hasEditedPoint).toBe(true);
  await page.getByRole('button',{name:/^Edit the (areas|regions) on page 1$/}).click();
  // No Full page button (owner 2026-10-26): erase every area, then Enter.
  await page.keyboard.press('e');
  const editAreas=page.locator('[data-region-edit-layer] [data-region-id]');
  for(let guard=0;guard<12&&await editAreas.count();guard+=1){const b=await editAreas.first().boundingBox();await page.mouse.click(b.x+b.width/2,b.y+b.height/2);}
  await expect(editAreas).toHaveCount(0);
  await page.keyboard.press('Enter');
  await expect(page.locator('[data-region-edit-layer]')).toHaveCount(0);
  await expect.poll(()=>page.evaluate(()=>{const key=Object.keys(localStorage).find(value=>value.startsWith('pdfSidebar_order-pages.pdf'));return JSON.parse(localStorage.getItem(key)).spaces.find(space=>space.id==='fix19-space-a').assignedPages[0].wholePageIncluded;})).toBe(true);
});
