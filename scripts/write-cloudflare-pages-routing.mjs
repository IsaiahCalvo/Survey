#!/usr/bin/env node
// Writes dist/_routes.json and dist/_headers for Cloudflare Pages.
//
// functions/_middleware.js sits at the root, so by default Pages would run a
// function for every request, including every script, image and font. Those
// count toward the Workers free plan's 100,000 requests a day. This keeps
// static files (hashed assets, OCR data, icons, images) off the function, and
// gives them the same headers the middleware would have set, taken from
// functions/_lib/securityHeaders.js so the two can't drift.
//
// HTML pages, app routes, /api, /mcp and /.well-known still run the function
// (SPA fallback, redirects, per-page CSP).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Directories whose files are all static (no HTML pages to route).
const STATIC_DIRS = ['assets', 'ocr', 'brand-gold', 'nightly'];
// Files Pages treats specially or that must keep running through the function.
// robots.txt, sitemap.xml and favicon.ico differ by host: kalvoe.com gets the
// suite's copies from public/kal-voe/ through the middleware.
const NEVER_EXCLUDE = new Set(['_routes.json', '_headers', '_redirects', '404.html', 'index.html', 'robots.txt', 'sitemap.xml', 'favicon.ico']);
const MAX_RULES = 100; // Cloudflare's limit for _routes.json and for _headers
const MAX_RULE_CHARS = 100;

function listStaticFiles(distDir) {
  const out = [];
  const walk = (dir, rel) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.name.startsWith('.')) continue;
      const relPath = rel ? `${rel}/${entry.name}` : entry.name;
      if (entry.isDirectory()) {
        if (!rel && STATIC_DIRS.includes(entry.name)) continue;
        walk(path.join(dir, entry.name), relPath);
      } else if (!entry.name.endsWith('.html') && !NEVER_EXCLUDE.has(relPath)) {
        out.push(`/${relPath}`);
      }
    }
  };
  walk(distDir, '');
  return out.sort();
}

export async function buildPagesRouting(distDir, { headersForPath } = {}) {
  if (!headersForPath) {
    ({ headersForPath } = await import(
      pathToFileURL(path.join(repoRoot, 'functions/_lib/securityHeaders.js')).href
    ));
  }
  const dirRules = STATIC_DIRS
    .filter((d) => fs.existsSync(path.join(distDir, d)))
    .map((d) => `/${d}/*`);
  const fileRules = listStaticFiles(distDir).filter((p) => p.length <= MAX_RULE_CHARS);
  // One include rule plus excludes must fit in the limit; keep directories first.
  const exclude = [...dirRules, ...fileRules].slice(0, MAX_RULES - 1);

  const routes = { version: 1, include: ['/*'], exclude };

  const blocks = exclude.map((rule) => {
    const sample = rule.endsWith('/*') ? `${rule.slice(0, -1)}x` : rule;
    const headers = headersForPath(sample);
    const lines = Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`);
    return `${rule}\n${lines.join('\n')}`;
  });
  const headersFile =
    '# Generated by scripts/write-cloudflare-pages-routing.mjs. Do not edit.\n' +
    '# Headers for static files that skip functions/_middleware.js.\n\n' +
    blocks.join('\n\n') + '\n';
  return { routes, headersFile };
}

async function main() {
  const distDir = path.resolve(process.argv[2] || path.join(repoRoot, 'dist'));
  if (!fs.existsSync(distDir)) throw new Error(`No build output at ${distDir}`);
  const { routes, headersFile } = await buildPagesRouting(distDir);
  fs.writeFileSync(path.join(distDir, '_routes.json'), JSON.stringify(routes, null, 2) + '\n');
  fs.writeFileSync(path.join(distDir, '_headers'), headersFile);
  console.log(`Cloudflare Pages routing: ${routes.exclude.length} static paths skip the function.`);
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
