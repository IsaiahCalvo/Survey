#!/usr/bin/env node

import { execFileSync } from 'node:child_process';
import {
  chmodSync,
  renameSync,
  writeFileSync,
} from 'node:fs';
import { dirname, resolve } from 'node:path';
import { randomUUID } from 'node:crypto';
import { loadEnv } from 'vite';

function mainRepositoryRoot() {
  const commonGitDir = execFileSync(
    'git',
    ['rev-parse', '--path-format=absolute', '--git-common-dir'],
    { encoding: 'utf8' },
  ).trim();
  return commonGitDir.endsWith('/.git') ? dirname(commonGitDir) : process.cwd();
}

function requireValue(environment, name) {
  const value = String(environment[name] || '').trim();
  if (!value) {
    throw new Error(`[TEST_ENV] Missing ${name} in the main repository .env/.env.local`);
  }
  return value;
}

const sourceRoot = mainRepositoryRoot();
const sourceEnvironment = loadEnv('development', sourceRoot, '');
const supabaseUrl = requireValue(sourceEnvironment, 'VITE_SUPABASE_URL');
const anonKey = requireValue(sourceEnvironment, 'VITE_SUPABASE_ANON_KEY');
const serviceKey = requireValue(sourceEnvironment, 'SUPABASE_SERVICE_ROLE_KEY');
const host = new URL(supabaseUrl).hostname;
if (host !== 'cvamwtpsuvxvjdnotbeg.supabase.co') {
  throw new Error(`[TEST_ENV] Refusing non-main Survey host "${host}"`);
}

const outputPath = resolve(process.cwd(), '.env.test');
const temporaryPath = `${outputPath}.${process.pid}.${randomUUID()}.tmp`;
const body = [
  '# Generated by scripts/configure-main-integration-env.mjs. Gitignored.',
  'SUPABASE_TEST_TARGET=main-isolated',
  `SUPABASE_TEST_URL=${supabaseUrl}`,
  `SUPABASE_TEST_ANON_KEY=${anonKey}`,
  `SUPABASE_TEST_SERVICE_KEY=${serviceKey}`,
  `SUPABASE_PRIVACY_PROBE_URL=${supabaseUrl}`,
  `SUPABASE_PRIVACY_PROBE_SERVICE_KEY=${serviceKey}`,
  '',
].join('\n');

writeFileSync(temporaryPath, body, { flag: 'wx', mode: 0o600 });
renameSync(temporaryPath, outputPath);
chmodSync(outputPath, 0o600);
console.log(`[TEST_ENV] Main Survey integration environment configured at ${outputPath}`);
